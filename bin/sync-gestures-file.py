#!/usr/bin/env python3
import argparse
import os
import re
import subprocess
import sys


def hypr_instance_signature():
    uid = os.getuid()
    hypr_dir = f"/run/user/{uid}/hypr"
    try:
        socks = [os.path.join(hypr_dir, d, ".socket.sock") for d in os.listdir(hypr_dir)]
        socks = [s for s in socks if os.path.exists(s)]
        if not socks:
            return None
        # pick most recently modified
        socks.sort(key=lambda s: os.stat(s).st_mtime, reverse=True)
        m = re.search(r"/hypr/([^/]+)/\.socket\.sock", socks[0])
        return m.group(1) if m else None
    except FileNotFoundError:
        return None


def ensure_required(input_path, marker):
    if not os.path.isfile(input_path):
        return False
    with open(input_path) as f:
        text = f.read()
    if marker in text:
        return True
    with open(input_path, "a") as f:
        f.write(f"\n{marker}\n")
    return True


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--enabled", choices=["true", "false"], required=True)
    parser.add_argument("--left", default="+1")
    parser.add_argument("--right", default="-1")
    parser.add_argument("--input", default=os.path.expanduser("~/.config/hypr/input.lua"))
    parser.add_argument("--output", default=os.path.expanduser("~/.config/hypr/control-panel-gestures.lua"))
    args = parser.parse_args()

    enabled = args.enabled == "true"
    output_dir = os.path.dirname(args.output)
    os.makedirs(output_dir, exist_ok=True)

    if enabled:
        content = f'''-- Generated by omarchy-control-panel. Safe to delete.
local function ocp_swipe(dir)
  local distance, triggered = 0, false
  local function consume(event)
    if triggered then return end
    distance = distance + math.abs(event.delta.x)
    if distance >= 25 then
      triggered = true
      hl.dispatch(hl.dsp.focus({{ workspace = dir }}))
    end
  end
  return {{
    start = function(e) distance = 0; triggered = false; consume(e) end,
    update = consume,
    finish = function() distance = 0; triggered = false end,
  }}
end
hl.gesture({{ fingers = 3, direction = "left", action = ocp_swipe("{args.left}") }})
hl.gesture({{ fingers = 3, direction = "right", action = ocp_swipe("{args.right}") }})
'''
    else:
        content = '-- Generated by omarchy-control-panel. Swipe3 is currently disabled.\n'

    with open(args.output, "w") as f:
        f.write(content)

    marker = 'require("hypr.control-panel-gestures")'
    if not ensure_required(args.input, marker):
        print(f"Could not ensure marker in {args.input}", file=sys.stderr)
        sys.exit(1)

    if enabled:
        sig = hypr_instance_signature()
        if sig:
            env = os.environ.copy()
            env["HYPRLAND_INSTANCE_SIGNATURE"] = sig
            subprocess.run(["hyprctl", "reload"], env=env, check=False)


if __name__ == "__main__":
    main()
